/* Focused settings flow, isolated accounts and real pending feedback; local only. */
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),readline=require('node:readline');
const assert=require('node:assert/strict');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'ig-settings-'));
let child,browser;
(async()=>{
  child=spawn('python3',[path.join(__dirname,'publication_browser_fixture.py'),root],{stdio:['ignore','pipe','inherit'],env:{...process.env,PYTHONDONTWRITEBYTECODE:'1'}});
  const lines=readline.createInterface({input:child.stdout});
  const config=await Promise.race([new Promise((resolve,reject)=>{lines.once('line',line=>{try{resolve(JSON.parse(line));}catch(e){reject(e);}});child.once('exit',code=>reject(Error('Fixture exited '+code)));}),new Promise((_,reject)=>setTimeout(()=>reject(Error('Fixture timeout')),10000).unref())]);lines.close();
  browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:1440,height:1050},timezoneId:'America/Sao_Paulo'});
  const errors=[],blocked=[],checks=[];
  await context.route('**/*',route=>{if(new URL(route.request().url()).origin!==config.url){blocked.push('external');return route.abort();}return route.continue();});
  const page=await context.newPage();page.setDefaultTimeout(8000);
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',msg=>{if(msg.type()==='error' && /Content Security Policy|Refused to|Uncaught/.test(msg.text()))errors.push(msg.text());});
  page.on('request',r=>{if(r.headers()['x-editorial-action']==='check')checks.push(new URL(r.url()).pathname);});
  await page.goto(config.url+'/panel');await page.getByLabel('Senha').fill('synthetic-browser-publication-password');
  await page.getByRole('button',{name:'Entrar',exact:true}).click();await page.locator('#messages').waitFor();
  assert.equal(await page.locator('#check-publication').count(),0);
  await page.getByRole('link',{name:'Configurações Meta',exact:true}).click();
  assert.equal(new URL(page.url()).search,'?view=settings');
  assert.equal(await page.locator('#messages').count(),0);
  assert.equal(await page.locator('#check-publication').count(),1);
  assert.equal(await page.getByRole('link',{name:'Configurações Meta',exact:true}).getAttribute('aria-current'),'page');
  assert.equal(checks.length,0,'opening settings cannot call the diagnostic');
  let seen,release;const received=new Promise(resolve=>seen=resolve),held=new Promise(resolve=>release=resolve);
  await page.route('**/editorial/api/drafts',async route=>{seen();await held;await route.continue();},{times:1});
  await page.locator('#check-publication').click();await received;
  assert.equal(await page.locator('#check-publication').isDisabled(),true);
  assert.equal(await page.locator('#check-publication').innerText(),'Verificando…');
  assert.equal(await page.locator('#ui-feedback').getAttribute('data-active'),'true');
  await page.locator('#check-publication').evaluate(node=>node.click());release();
  await page.locator('#publication-check-feedback').filter({hasText:'Verificação concluída: acesso de publicação confirmado.'}).waitFor();
  assert.equal(checks.length,1);assert.equal(await page.locator('#check-publication').isEnabled(),true);
  assert.match(await page.locator('#publication-checked-at').innerText(),/Última consulta: .*\(Brasília\)/);
  await page.reload();assert.equal(checks.length,1);
  assert.match(await page.locator('#publication-status').innerText(),/Token e permissão/);
  await page.locator('#check-publication').click();await page.locator('#publication-check-feedback').filter({hasText:'Verificação concluída: acesso de publicação confirmado.'}).waitFor();
  assert.equal(checks.length,2,'same result is explicitly acknowledged');
  const message=await page.locator('#publication-status').innerText();
  await page.route('**/editorial/api/drafts',route=>route.fulfill({status:504,contentType:'text/html',body:'<h1>private proxy text</h1>'}),{times:1});
  await page.locator('#check-publication').click();
  await page.locator('#publication-check-feedback').filter({hasText:'Não foi possível concluir a consulta. Tente novamente em instantes.'}).waitFor();
  assert.equal(await page.locator('#publication-status').innerText(),message);
  assert.equal(await page.locator('#check-publication').isEnabled(),true);
  assert(!(await page.locator('body').innerText()).includes('private proxy text'));
  console.log('PASS separate settings: no automatic queries, pending feedback, duplicate lock, same-result acknowledgement, cached reload and safe proxy errors');
  const second='/accounts/'+config.second;
  await page.goto(config.url+second+'/panel?view=settings');
  assert.equal(await page.locator('.account').innerText(),'@second_account');
  assert.match(await page.locator('#publication-status').innerText(),/Sem consulta manual recente/);
  await page.locator('#check-publication').click();await page.locator('#publication-check-feedback').filter({hasText:'Verificação concluída: acesso de publicação confirmado.'}).waitFor();
  assert.equal(checks.at(-1),second+'/editorial/api/drafts');
  await page.getByRole('link',{name:'Caixa de entrada',exact:true}).click();
  assert.equal(new URL(page.url()).pathname,second+'/panel');
  assert.equal(await page.locator('#check-publication').count(),0);
  await page.goto(config.url+second+'/panel#connection');await page.waitForURL('**/panel?view=settings');
  assert.equal(new URL(page.url()).pathname,second+'/panel');
  const result=await (await page.request.get(config.url+'/__publication_test')).json();
  assert.deepEqual(result.checks,['umdoislab','umdoislab',config.second]);
  assert.equal(result.published.length,0);
  const evidence=process.env.IG_EVIDENCE_DIR || root;fs.mkdirSync(evidence,{recursive:true});
  await page.screenshot({path:path.join(evidence,'settings-desktop.png'),fullPage:true});
  await page.emulateMedia({reducedMotion:'reduce'});await page.setViewportSize({width:390,height:844});
  await page.locator('.ui-menu-toggle').click();
  assert.equal(await page.getByRole('link',{name:'Caixa de entrada',exact:true}).isVisible(),true);
  await page.locator('.ui-menu-toggle').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(evidence,'settings-mobile.png'),fullPage:true});
  await page.locator('.ui-menu-toggle').click();
  await page.getByRole('link',{name:'Visão geral',exact:true}).click();
  await page.waitForURL('**/editorial/#overview');
  await page.waitForFunction(()=>document.body && document.getElementById('principal') && !document.body.dataset.uiLoading);
  assert.equal(await page.locator('#check-publication').count(),0);
  assert.equal(await page.getByText('Publicação sob seu controle',{exact:true}).count(),0);
  assert.equal(blocked.length,0);assert.deepEqual(errors,[]);
  console.log('PASS secondary account, legacy bookmark, clean Editorial, reduced motion/mobile layout, no publication or external requests, CSP/console clean');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{
  if(browser)await browser.close();if(child && child.exitCode===null){const done=new Promise(resolve=>child.once('exit',resolve));child.kill('SIGTERM');await done;}
  fs.rmSync(root,{recursive:true,force:true});
});
